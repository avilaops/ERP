ALTER TABLE state_tax_rates DROP CONSTRAINT state_tax_rates_pkey;
ALTER TABLE state_tax_rates ADD PRIMARY KEY (line_id, uf);

-- Equipamento e versão publicada dizem de qual linha são. A numeração das versões
-- continua uma só na empresa: o pedido guarda o número e, por ele, a linha.
ALTER TABLE products ADD COLUMN line_id integer NOT NULL DEFAULT 1 REFERENCES product_lines (id);
CREATE INDEX products_line_id_idx ON products (line_id);
ALTER TABLE price_table_versions ADD COLUMN line_id integer NOT NULL DEFAULT 1 REFERENCES product_lines (id);
CREATE INDEX price_table_versions_line_id_idx ON price_table_versions (line_id, version DESC);
