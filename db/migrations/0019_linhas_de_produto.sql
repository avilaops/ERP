-- Linhas de produto: a mesma empresa vende mais de uma linha (importada, nacional…),
-- e cada linha tem os seus parâmetros, as suas alíquotas por estado, os seus
-- equipamentos e a sua tabela publicada. Um pedido é de uma linha só: a da versão
-- da tabela com que ele foi aberto.
-- Sem nome de esquema: cada empresa tem estas tabelas no esquema dela.

CREATE TABLE product_lines (
    id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       text NOT NULL CHECK (btrim(name) <> ''),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by text NOT NULL CHECK (btrim(updated_by) <> '')
);
CREATE UNIQUE INDEX product_lines_name_idx ON product_lines (lower(btrim(name)));

